-- ================================================================
-- LIGA POKEMON - MODELO RELACIONAL PARA AULAS DE SQL
-- PostgreSQL 14+ | 19 tabelas | UTF-8
-- Execute em um banco de dados vazio, conectado como um usuario
-- que tenha permissao CREATE no schema public.
-- Reexecucao segura: DROP SCHEMA EXCLUSIVO + CREATE SCHEMA.
-- ATENCAO: a opcao abaixo APAGA o schema liga_pokemon e seus dados.
-- ================================================================

BEGIN;

DROP SCHEMA IF EXISTS liga_pokemon CASCADE;
CREATE SCHEMA liga_pokemon;
SET search_path TO liga_pokemon, public;

-- 1. MUNDO POKEMON -------------------------------------------------
CREATE TABLE regiao (
    id_regiao       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(80) NOT NULL UNIQUE,
    clima           VARCHAR(80)
);

CREATE TABLE especie (
    id_especie      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(100) NOT NULL UNIQUE,
    raridade        VARCHAR(15) NOT NULL DEFAULT 'COMUM',
    id_regiao       INTEGER NOT NULL REFERENCES regiao(id_regiao),
    CONSTRAINT ck_especie_raridade CHECK (raridade IN ('COMUM', 'INCOMUM', 'RARA', 'LENDARIA'))
);

CREATE TABLE tipo (
    id_tipo         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE especie_tipo (
    id_especie      INTEGER NOT NULL REFERENCES especie(id_especie) ON DELETE CASCADE,
    id_tipo         INTEGER NOT NULL REFERENCES tipo(id_tipo),
    PRIMARY KEY (id_especie, id_tipo)
);

-- Autorrelacionamento: uma especie pode evoluir para outra.
CREATE TABLE evolucao (
    id_origem       INTEGER NOT NULL REFERENCES especie(id_especie),
    id_destino      INTEGER NOT NULL REFERENCES especie(id_especie),
    nivel_minimo    SMALLINT,
    item_necessario VARCHAR(100),
    PRIMARY KEY (id_origem, id_destino),
    CONSTRAINT ck_evolucao_distinta CHECK (id_origem <> id_destino),
    CONSTRAINT ck_evolucao_nivel CHECK (nivel_minimo IS NULL OR nivel_minimo >= 1),
    CONSTRAINT ck_evolucao_condicao CHECK (nivel_minimo IS NOT NULL OR item_necessario IS NOT NULL)
);

-- 2. TREINADORES E CAPTURAS ----------------------------------------
CREATE TABLE treinador (
    id_treinador    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(120) NOT NULL,
    cidade          VARCHAR(100),
    data_cadastro   DATE NOT NULL DEFAULT CURRENT_DATE,
    id_regiao       INTEGER NOT NULL REFERENCES regiao(id_regiao)
);

CREATE TABLE pokemon (
    id_pokemon      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apelido         VARCHAR(100),
    nivel           SMALLINT NOT NULL DEFAULT 1,
    experiencia     INTEGER NOT NULL DEFAULT 0,
    id_especie      INTEGER NOT NULL REFERENCES especie(id_especie),
    id_treinador    INTEGER REFERENCES treinador(id_treinador) ON DELETE SET NULL,
    CONSTRAINT ck_pokemon_nivel CHECK (nivel BETWEEN 1 AND 100),
    CONSTRAINT ck_pokemon_experiencia CHECK (experiencia >= 0)
);

-- Historico do evento de captura; o treinador atual fica em pokemon.
CREATE TABLE captura (
    id_captura      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pokemon      INTEGER NOT NULL UNIQUE REFERENCES pokemon(id_pokemon),
    id_treinador    INTEGER NOT NULL REFERENCES treinador(id_treinador),
    data_captura    TIMESTAMP NOT NULL,
    id_regiao       INTEGER NOT NULL REFERENCES regiao(id_regiao),
    metodo          VARCHAR(40) NOT NULL DEFAULT 'POKEBOLA',
    CONSTRAINT ck_captura_metodo CHECK (metodo IN ('POKEBOLA', 'GREAT_BALL', 'ULTRA_BALL', 'MASTER_BALL', 'OUTRO'))
);

-- 3. GOLPES --------------------------------------------------------
CREATE TABLE golpe (
    id_golpe        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(100) NOT NULL UNIQUE,
    poder           SMALLINT NOT NULL DEFAULT 0,
    precisao        NUMERIC(5,2) NOT NULL DEFAULT 100,
    categoria       VARCHAR(10) NOT NULL,
    id_tipo         INTEGER NOT NULL REFERENCES tipo(id_tipo),
    CONSTRAINT ck_golpe_poder CHECK (poder >= 0),
    CONSTRAINT ck_golpe_precisao CHECK (precisao BETWEEN 0 AND 100),
    CONSTRAINT ck_golpe_categoria CHECK (categoria IN ('FISICO', 'ESPECIAL', 'STATUS'))
);

CREATE TABLE especie_golpe (
    id_especie        INTEGER NOT NULL REFERENCES especie(id_especie) ON DELETE CASCADE,
    id_golpe          INTEGER NOT NULL REFERENCES golpe(id_golpe),
    nivel_aprendizado SMALLINT NOT NULL DEFAULT 1,
    PRIMARY KEY (id_especie, id_golpe),
    CONSTRAINT ck_especie_golpe_nivel CHECK (nivel_aprendizado BETWEEN 1 AND 100)
);

CREATE TABLE pokemon_golpe (
    id_pokemon       INTEGER NOT NULL REFERENCES pokemon(id_pokemon) ON DELETE CASCADE,
    id_golpe         INTEGER NOT NULL REFERENCES golpe(id_golpe),
    data_aprendizado DATE NOT NULL,
    PRIMARY KEY (id_pokemon, id_golpe)
);

-- 4. EQUIPES -------------------------------------------------------
CREATE TABLE equipe (
    id_equipe       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(100) NOT NULL,
    id_treinador    INTEGER NOT NULL REFERENCES treinador(id_treinador),
    data_criacao    DATE NOT NULL DEFAULT CURRENT_DATE,
    UNIQUE (id_equipe, id_treinador),
    UNIQUE (id_treinador, nome)
);

-- Linhas historicas: a mesma dupla equipe/pokemon pode reaparecer.
CREATE TABLE equipe_pokemon (
    id_equipe_pokemon INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_equipe       INTEGER NOT NULL REFERENCES equipe(id_equipe) ON DELETE CASCADE,
    id_pokemon      INTEGER NOT NULL REFERENCES pokemon(id_pokemon),
    data_entrada    DATE NOT NULL,
    data_saida      DATE,
    CONSTRAINT ck_equipe_datas CHECK (data_saida IS NULL OR data_saida >= data_entrada),
    UNIQUE (id_equipe, id_pokemon, data_entrada)
);

-- Um pokemon so pode ter uma alocacao ATIVA (data_saida IS NULL).
CREATE UNIQUE INDEX ux_equipe_pokemon_ativo
    ON equipe_pokemon (id_pokemon) WHERE data_saida IS NULL;

-- 5. TORNEIOS E BATALHAS -------------------------------------------
CREATE TABLE torneio (
    id_torneio      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(150) NOT NULL,
    data_inicio     DATE NOT NULL,
    data_fim        DATE NOT NULL,
    premiacao       NUMERIC(14,2) NOT NULL DEFAULT 0,
    id_regiao       INTEGER NOT NULL REFERENCES regiao(id_regiao),
    CONSTRAINT ck_torneio_datas CHECK (data_fim >= data_inicio),
    CONSTRAINT ck_torneio_premiacao CHECK (premiacao >= 0)
);

CREATE TABLE inscricao (
    id_inscricao    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_torneio      INTEGER NOT NULL REFERENCES torneio(id_torneio),
    id_treinador    INTEGER NOT NULL REFERENCES treinador(id_treinador),
    id_equipe       INTEGER NOT NULL,
    data_inscricao  DATE NOT NULL,
    -- A equipe inscrita precisa pertencer ao treinador da inscricao.
    CONSTRAINT fk_inscricao_equipe_treinador FOREIGN KEY (id_equipe, id_treinador)
        REFERENCES equipe (id_equipe, id_treinador),
    UNIQUE (id_torneio, id_treinador),
    UNIQUE (id_inscricao, id_torneio)
);

CREATE TABLE batalha (
    id_batalha      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_torneio      INTEGER NOT NULL REFERENCES torneio(id_torneio),
    data_hora       TIMESTAMP NOT NULL,
    fase            VARCHAR(40) NOT NULL,
    duracao_segundos INTEGER,
    situacao        VARCHAR(12) NOT NULL DEFAULT 'AGENDADA',
    CONSTRAINT ck_batalha_duracao CHECK (duracao_segundos IS NULL OR duracao_segundos > 0),
    CONSTRAINT ck_batalha_situacao CHECK (situacao IN ('AGENDADA', 'CONCLUIDA', 'CANCELADA')),
    UNIQUE (id_batalha, id_torneio)
);

-- id_torneio adicional permite FKs compostas que impedem
-- inscricao de outro torneio de participar da batalha.
CREATE TABLE participacao_batalha (
    id_participacao INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_batalha      INTEGER NOT NULL,
    id_inscricao    INTEGER NOT NULL,
    id_torneio      INTEGER NOT NULL,
    resultado       VARCHAR(8),
    CONSTRAINT fk_part_batalha FOREIGN KEY (id_batalha, id_torneio)
        REFERENCES batalha(id_batalha, id_torneio),
    CONSTRAINT fk_part_inscricao FOREIGN KEY (id_inscricao, id_torneio)
        REFERENCES inscricao(id_inscricao, id_torneio),
    CONSTRAINT ck_part_resultado CHECK (resultado IS NULL OR resultado IN ('VITORIA', 'DERROTA', 'EMPATE')),
    UNIQUE (id_batalha, id_inscricao)
);

CREATE TABLE uso_pokemon (
    id_uso          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_participacao INTEGER NOT NULL REFERENCES participacao_batalha(id_participacao) ON DELETE CASCADE,
    id_pokemon      INTEGER NOT NULL REFERENCES pokemon(id_pokemon),
    dano_total      INTEGER NOT NULL DEFAULT 0,
    foi_derrotado   BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_uso_dano CHECK (dano_total >= 0),
    UNIQUE (id_participacao, id_pokemon)
);

CREATE TABLE evento_batalha (
    id_evento       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_uso          INTEGER NOT NULL REFERENCES uso_pokemon(id_uso) ON DELETE CASCADE,
    id_golpe        INTEGER NOT NULL REFERENCES golpe(id_golpe),
    rodada          INTEGER NOT NULL,
    dano            INTEGER NOT NULL DEFAULT 0,
    foi_critico     BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_evento_rodada CHECK (rodada >= 1),
    CONSTRAINT ck_evento_dano CHECK (dano >= 0)
);

-- INDICES PARA JOINS E FILTROS FREQUENTES --------------------------
CREATE INDEX ix_especie_regiao ON especie(id_regiao);
CREATE INDEX ix_especie_tipo_tipo ON especie_tipo(id_tipo);
CREATE INDEX ix_evolucao_destino ON evolucao(id_destino);
CREATE INDEX ix_treinador_regiao ON treinador(id_regiao);
CREATE INDEX ix_pokemon_treinador ON pokemon(id_treinador);
CREATE INDEX ix_pokemon_especie ON pokemon(id_especie);
CREATE INDEX ix_captura_treinador ON captura(id_treinador);
CREATE INDEX ix_captura_regiao_data ON captura(id_regiao, data_captura);
CREATE INDEX ix_golpe_tipo ON golpe(id_tipo);
CREATE INDEX ix_especie_golpe_golpe ON especie_golpe(id_golpe);
CREATE INDEX ix_pokemon_golpe_golpe ON pokemon_golpe(id_golpe);
CREATE INDEX ix_equipe_treinador ON equipe(id_treinador);
CREATE INDEX ix_equipe_pokemon_equipe ON equipe_pokemon(id_equipe);
CREATE INDEX ix_torneio_regiao ON torneio(id_regiao);
CREATE INDEX ix_inscricao_treinador ON inscricao(id_treinador);
CREATE INDEX ix_inscricao_equipe ON inscricao(id_equipe);
CREATE INDEX ix_batalha_torneio_data ON batalha(id_torneio, data_hora);
CREATE INDEX ix_participacao_inscricao ON participacao_batalha(id_inscricao);
CREATE INDEX ix_uso_pokemon_pokemon ON uso_pokemon(id_pokemon);
CREATE INDEX ix_evento_uso_rodada ON evento_batalha(id_uso, rodada);
CREATE INDEX ix_evento_golpe ON evento_batalha(id_golpe);

-- REGRAS ADICIONAIS: triggers para participantes -------------------
-- No maximo dois participantes por batalha, sem treinador repetido.
-- A checagem exata de dois participantes e resultado consistente
-- e feita quando a batalha e marcada como CONCLUIDA.
CREATE OR REPLACE FUNCTION validar_participacao_batalha()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    v_treinador INTEGER;
BEGIN
    SELECT i.id_treinador INTO v_treinador
      FROM inscricao i WHERE i.id_inscricao = NEW.id_inscricao;

    IF EXISTS (
        SELECT 1 FROM participacao_batalha pb
        JOIN inscricao i ON i.id_inscricao = pb.id_inscricao
        WHERE pb.id_batalha = NEW.id_batalha
          AND pb.id_participacao <> COALESCE(NEW.id_participacao, -1)
          AND i.id_treinador = v_treinador
    ) THEN
        RAISE EXCEPTION 'Um treinador nao pode enfrentar a si mesmo na batalha %', NEW.id_batalha;
    END IF;

    IF (SELECT COUNT(*) FROM participacao_batalha pb
        WHERE pb.id_batalha = NEW.id_batalha
          AND pb.id_participacao <> COALESCE(NEW.id_participacao, -1)) >= 2 THEN
        RAISE EXCEPTION 'Uma batalha pode ter no maximo dois participantes';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validar_participacao
BEFORE INSERT OR UPDATE OF id_batalha, id_inscricao
ON participacao_batalha
FOR EACH ROW EXECUTE FUNCTION validar_participacao_batalha();

CREATE OR REPLACE FUNCTION validar_conclusao_batalha()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    v_total INTEGER;
    v_vitorias INTEGER;
    v_derrotas INTEGER;
    v_empates INTEGER;
BEGIN
    IF NEW.situacao = 'CONCLUIDA' THEN
        SELECT COUNT(*),
               COUNT(*) FILTER (WHERE resultado = 'VITORIA'),
               COUNT(*) FILTER (WHERE resultado = 'DERROTA'),
               COUNT(*) FILTER (WHERE resultado = 'EMPATE')
          INTO v_total, v_vitorias, v_derrotas, v_empates
          FROM participacao_batalha
         WHERE id_batalha = NEW.id_batalha;
        IF v_total <> 2 OR NOT (
            (v_vitorias = 1 AND v_derrotas = 1) OR v_empates = 2
        ) THEN
            RAISE EXCEPTION 'Batalha concluida exige dois participantes e resultados compativeis';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validar_conclusao
BEFORE INSERT OR UPDATE OF situacao ON batalha
FOR EACH ROW EXECUTE FUNCTION validar_conclusao_batalha();

