CREATE SCHEMA Loja;

CREATE TABLE FORNECEDOR(

    FNUM INT(3) NOT NULL,
    FNOME VARCHAR(25),
    CIDADE VARCHAR(25),
    PRIMARY KEY (FNUM)
);

CREATE TABLE PECA(

    PNUM INT(3) NOT NULL,
    COR VARCHAR(15),
    PESO FLOAT,
    CIDADE VARCHAR (15),
    PRIMARY KEY (PNUM)
);

CREATE TABLE VENDE(
    FNUM INT(3) NOT NULL,
    PNUM INT(3) NOT NULL,
    QUANTIDADE INT(3),
    PRIMARY KEY (FNUM, PNUM),
    FOREIGN KEY (FNUM) REFERENCES FORNECEDOR (FNUM) ON DELETE SET NULL ON UPDATE SET NULL,
    FOREIGN KEY (PNUM) REFERENCES PECA (PNUM) ON DELETE SET NULL ON UPDATE SET NULL,
);